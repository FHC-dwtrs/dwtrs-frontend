export type TKey = keyof typeof T.en

// ── Context ────────────────────────────────────────────
interface LangCtx {
  lang: Lang
  setLang: (l: Lang) => void
  t: (key: TKey) => string
}

const LangContext = createContext<LangCtx>({
  lang: 'en',
  setLang: () => {},
  t: (k) => T.en[k],
})

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>('en')
  const t = (key: TKey): string => T[lang][key] ?? T.en[key]
  return <LangContext.Provider value={{ lang, setLang, t }}>{children}</LangContext.Provider>
}

export function useLanguage() {
  return useContext(LangContext)
}

// ── Language Toggle Button ─────────────────────────────
export function LangToggle({ className = '' }: { className?: string }) {
  const { lang, setLang } = useLanguage()
  return (
    <button
      onClick={() => setLang(lang === 'en' ? 'am' : 'en')}
      className={`inline-flex items-center gap-1.5 px-3 py-1.5 rounded-full border text-xs font-bold transition-all duration-200 ${className}`}
      title={lang === 'en' ? 'Switch to Amharic' : 'Switch to English'}
    >
      <span className="text-sm">{lang === 'en' ? '🇪🇹' : '🇬🇧'}</span>
      <span>{lang === 'en' ? 'አማርኛ' : 'English'}</span>
    </button>
  )
}
